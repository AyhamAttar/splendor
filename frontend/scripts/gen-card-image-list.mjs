// Lists the real card art in public/assets/Cards/ into src/lib/cardImageList.ts.
// Re-run after adding/removing card images:  node scripts/gen-card-image-list.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dir = resolve(root, "public/assets/Cards");
const files = readdirSync(dir)
  .filter((f) => /\.(jpe?g|png|webp|avif)$/i.test(f))
  .sort();

const body = `// AUTO-GENERATED by scripts/gen-card-image-list.mjs — do not edit by hand.
// Real card artwork living in public/assets/Cards/. Re-run the script after
// changing that folder.
export const CARD_IMAGE_FILES: string[] = [
${files.map((f) => `  ${JSON.stringify(f)},`).join("\n")}
];
`;
writeFileSync(resolve(root, "src/lib/cardImageList.ts"), body);
console.log(`wrote src/lib/cardImageList.ts with ${files.length} images`);
